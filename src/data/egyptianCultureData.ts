export type CultureLang = 'en' | 'ar' | 'fr' | 'de' | 'it' | 'es' | 'zh' | 'ru';

export interface CultureLocalizedContent {
  name: string;
  epithet: string;
  summary: string;
  bio: string;
  quote: string;
  achievements: string[];
  eraLabel?: string;
}

export interface CultureIconEntry {
  id: string;
  sectionId: string;
  era: string;
  image?: string;
  link: string;
  locales: Record<CultureLang, CultureLocalizedContent>;
}

export interface CultureSectionMeta {
  id: string;
  titles: Record<CultureLang, string>;
}

