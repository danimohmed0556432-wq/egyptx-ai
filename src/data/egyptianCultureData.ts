export const SUPPORTED_CULTURE_LANGS: CultureLang[] = ['en', 'ar', 'fr', 'de', 'it', 'es', 'zh', 'ru'];

export function resolveCultureLang(locale?: string | null): CultureLang {
  const code = String(locale || 'en').toLowerCase().slice(0, 2) as CultureLang;
  return SUPPORTED_CULTURE_LANGS.includes(code) ? code : 'en';
}

